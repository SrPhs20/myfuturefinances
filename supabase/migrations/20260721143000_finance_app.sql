create extension if not exists pgcrypto;

create table if not exists public.perfis (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nome text not null default '',
  avatar_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint perfis_user_id_key unique (user_id)
);

create table if not exists public.lancamentos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tipo text not null check (tipo in ('receita', 'despesa')),
  categoria text not null,
  descricao text not null,
  valor numeric(14,2) not null check (valor > 0),
  data date not null default current_date,
  origem text,
  origem_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contas_fixas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nome text not null,
  valor numeric(14,2) not null check (valor > 0),
  vencimento date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.metas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mes date not null default date_trunc('month', current_date)::date,
  valor numeric(14,2) not null check (valor > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint metas_user_mes_key unique (user_id, mes)
);

create table if not exists public.cartoes_parcelas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cartao_nome text not null,
  cartao_final text not null default '',
  descricao text not null,
  valor_total numeric(14,2) not null check (valor_total > 0),
  total_parcelas integer not null check (total_parcelas > 0),
  parcelas_pagas integer not null default 0 check (parcelas_pagas >= 0),
  data_primeira_parcela date not null,
  dia_vencimento integer not null check (dia_vencimento between 1 and 31),
  status text not null default 'ativo' check (status in ('ativo', 'quitado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cartoes_parcelas_quantidade_check check (parcelas_pagas <= total_parcelas)
);

