do $$
declare
  tabela text;
  politica record;
begin
  foreach tabela in array array['perfis', 'lancamentos', 'contas_fixas', 'metas', 'cartoes_parcelas']
  loop
    for politica in
      select policyname
      from pg_policies
      where schemaname = 'public' and tablename = tabela
    loop
      execute format('drop policy %I on public.%I', politica.policyname, tabela);
    end loop;
    execute format(
      'create policy "Usuários leem os próprios dados" on public.%I for select to authenticated using ((select auth.uid()) = user_id)',
      tabela
    );
    execute format(
      'create policy "Usuários inserem os próprios dados" on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)',
      tabela
    );
    execute format(
      'create policy "Usuários atualizam os próprios dados" on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)',
      tabela
    );
    execute format(
      'create policy "Usuários excluem os próprios dados" on public.%I for delete to authenticated using ((select auth.uid()) = user_id)',
      tabela
    );
  end loop;
end;
$$;

