create or replace function public.pagar_conta_fixa(p_conta_id bigint)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  conta public.contas_fixas%rowtype;
  novo_vencimento date;
begin
  select * into conta
  from public.contas_fixas
  where id = p_conta_id and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'Conta fixa não encontrada.';
  end if;

  novo_vencimento := (conta.vencimento + interval '1 month')::date;

  insert into public.lancamentos (user_id, tipo, categoria, descricao, valor, data, origem, origem_id)
  values (auth.uid(), 'despesa', 'Conta fixa', conta.nome, conta.valor, current_date, 'conta_fixa', conta.id);

  update public.contas_fixas
  set vencimento = novo_vencimento
  where id = conta.id and user_id = auth.uid();

  return jsonb_build_object('vencimento', novo_vencimento);
end;
$$;

create or replace function public.pagar_parcela_cartao(p_parcelamento_id bigint)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  compra public.cartoes_parcelas%rowtype;
  novas_pagas integer;
  valor_parcela numeric(14,2);
  novo_status text;
begin
  select * into compra
  from public.cartoes_parcelas
  where id = p_parcelamento_id and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'Parcelamento não encontrado.';
  end if;

  if compra.parcelas_pagas >= compra.total_parcelas then
    raise exception 'Este parcelamento já está quitado.';
  end if;

  novas_pagas := compra.parcelas_pagas + 1;
  valor_parcela := round(compra.valor_total / compra.total_parcelas, 2);
  novo_status := case when novas_pagas >= compra.total_parcelas then 'quitado' else 'ativo' end;

  insert into public.lancamentos (user_id, tipo, categoria, descricao, valor, data, origem, origem_id)
  values (
    auth.uid(),
    'despesa',
    'Cartão de crédito',
    format('%s - %s (%s/%s)', compra.cartao_nome, compra.descricao, novas_pagas, compra.total_parcelas),
    valor_parcela,
    current_date,
    'cartao',
    compra.id
  );

  update public.cartoes_parcelas
  set parcelas_pagas = novas_pagas, status = novo_status
  where id = compra.id and user_id = auth.uid();

  return jsonb_build_object('parcelas_pagas', novas_pagas, 'status', novo_status);
end;
$$;

create or replace function public.limpar_meus_dados()
returns void
language plpgsql
set search_path = public
as $$
begin
  delete from public.lancamentos where user_id = auth.uid();
  delete from public.contas_fixas where user_id = auth.uid();
  delete from public.metas where user_id = auth.uid();
  delete from public.cartoes_parcelas where user_id = auth.uid();
end;
$$;

create or replace function public.excluir_parcelamento_cartao(p_parcelamento_id bigint)
returns void
language plpgsql
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.cartoes_parcelas
    where id = p_parcelamento_id and user_id = auth.uid()
  ) then
    raise exception 'Parcelamento não encontrado.';
  end if;

  delete from public.lancamentos
  where user_id = auth.uid() and origem = 'cartao' and origem_id = p_parcelamento_id;

  delete from public.cartoes_parcelas
  where id = p_parcelamento_id and user_id = auth.uid();
end;
$$;

