create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  tabela text;
begin
  foreach tabela in array array['perfis', 'lancamentos', 'contas_fixas', 'metas', 'cartoes_parcelas']
  loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', tabela, tabela);
    execute format(
      'create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      tabela,
      tabela
    );
  end loop;
end;
$$;

create or replace function public.criar_perfil_novo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.perfis (user_id, nome)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'nome', ''), split_part(new.email, '@', 1))
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists criar_perfil_apos_cadastro on auth.users;
create trigger criar_perfil_apos_cadastro
after insert on auth.users
for each row execute function public.criar_perfil_novo_usuario();

